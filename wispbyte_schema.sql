-- ===========================================================================
-- wispcord / member-bot Supabase schema
--
-- Paste this whole file into the Supabase SQL Editor and press Run.
-- Safe to run more than once: every statement is idempotent.
--
-- Access model, in one paragraph. The member page runs in a browser with the
-- **anon** key, so anything it must read has to be readable by anon — and
-- anything it must write has to be insertable by anon. It may never read a
-- ticket back out (that would leak everyone's tickets to anyone with the public
-- key), so tickets are write-only from the browser. Staff reads go through the
-- admin bot's process, which holds the service key and bypasses RLS.
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. ticket_queue — new tickets submitted from the member page
-- ---------------------------------------------------------------------------
create table if not exists public.ticket_queue (
  id              bigint generated by default as identity primary key,
  ticket_id       text,
  category        text,
  subject         text,
  body            text,
  answers         jsonb default '{}'::jsonb,
  attachments     jsonb default '[]'::jsonb,
  discord_user_id text,
  discord_tag     text,
  anonymous       boolean default false,
  status          text default 'queued',
  created_at      timestamptz default now(),
  processed_at    timestamptz
);

create index if not exists ticket_queue_unprocessed_idx
  on public.ticket_queue (processed_at) where processed_at is null;

alter table public.ticket_queue enable row level security;

-- The browser may only ever ADD a ticket, never read one back.
drop policy if exists "anon can insert tickets" on public.ticket_queue;
create policy "anon can insert tickets"
  on public.ticket_queue
  for insert
  to anon
  with check (true);

drop policy if exists "service full access ticket_queue" on public.ticket_queue;
create policy "service full access ticket_queue"
  on public.ticket_queue
  for all
  to service_role
  using (true)
  with check (true);

