-- ---------------------------------------------------------------------------
-- 3. bot_status — the heartbeat table. The ONLY table anon may read.
-- ---------------------------------------------------------------------------
create table if not exists public.bot_status (
  id           text primary key,
  updated_at   timestamptz default now(),
  version      text,
  guild_count  integer default 0,
  member_count integer default 0,
  latency_ms   integer default 0
);

-- Added after the first release, so an existing table needs the ALTER:
-- `create table if not exists` does nothing to a table that is already there.
-- The member bot sends uptime_seconds with every heartbeat and retries without
-- it if the column is missing, so the heartbeat still lands either way — only
-- the uptime display on the site depends on this.
alter table public.bot_status add column if not exists uptime_seconds integer default 0;

alter table public.bot_status enable row level security;

-- The member page reads the 'member' row with the anon key to decide whether
-- to paint the bot dot green. Read only: no anon insert, update or delete.
drop policy if exists "anon can read bot status" on public.bot_status;
create policy "anon can read bot status"
  on public.bot_status
  for select
  to anon
  using (true);

drop policy if exists "service full access bot_status" on public.bot_status;
create policy "service full access bot_status"
  on public.bot_status
  for all
  to service_role
  using (true)
  with check (true);

-- Seed both rows so the page has something to read before the bots boot.
insert into public.bot_status (id, version) values ('member', '0.0.0')
  on conflict (id) do nothing;
insert into public.bot_status (id, version) values ('admin', '0.0.0')
  on conflict (id) do nothing;

